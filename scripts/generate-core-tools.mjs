/**
 * Generate src/core-tools.ts from the official WPS SkillHub MCP `tools/list`
 * snapshot (wps-mcp-tools.json). For each core tool it embeds the raw MCP
 * description verbatim and a sanitized `parameters` that stays inside the
 * enforced JSON-Schema subset accepted by DSH's `ctx.tools.register` /
 * `assertSupportedJsonSchema`.
 *
 * Run from the package root:
 *   node scripts/generate-core-tools.mjs <path-to-wps-mcp-tools.json>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SCHEMA_TYPES = ["object", "array", "string", "number", "integer", "boolean", "null"];
const ANNOTATIONS = ["description", "title", "default", "examples"];

function isPlainObject(v) {
  return v !== null && typeof v === "object" && !Array.isArray(v);
}

/**
 * Sanitize one MCP inputSchema node into the enforced JSON-Schema subset.
 * Unsupported vocabulary ($ref / anyOf / allOf / format / pattern / type
 * arrays / oneOf) collapses to an annotation-only schema ({description}), which
 * accepts any lossless JSON value. This keeps registration from ever failing
 * while preserving the useful typing the official schemas carry.
 */
function sanitize(node) {
  if (!isPlainObject(node)) return {};
  const out = {};
  for (const k of ANNOTATIONS) {
    if (node[k] !== undefined) out[k] = node[k];
  }
  const t = node.type;
  if (typeof t !== "string" || !SCHEMA_TYPES.includes(t)) {
    // annotation-only (unconstrained JSON)
    return out;
  }
  out.type = t;
  if (t === "object") {
    if (isPlainObject(node.properties)) {
      const props = {};
      for (const [key, child] of Object.entries(node.properties)) {
        props[key] = sanitize(child);
      }
      out.properties = props;
      if (Array.isArray(node.required)) {
        const required = node.required.filter(
          (r) => typeof r === "string" && Object.prototype.hasOwnProperty.call(props, r)
        );
        if (required.length > 0) out.required = required;
      }
    }
    if (typeof node.additionalProperties === "boolean") {
      out.additionalProperties = node.additionalProperties;
    }
  } else if (t === "array") {
    if (node.items !== undefined) out.items = sanitize(node.items);
  } else {
    // scalar: keep enum / const only when well-formed
    if (Array.isArray(node.enum) && node.enum.length > 0) out.enum = node.enum;
    if (node.const !== undefined) out.const = node.const;
  }
  return out;
}

